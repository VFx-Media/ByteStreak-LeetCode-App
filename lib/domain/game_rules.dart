import 'dart:math' as math;

import 'package:bytestreak/domain/models.dart';

/// League from global leaderboard position (plan §2: "Leaderboard and leagues").
enum League {
  gold('Gold League'),
  silver('Silver League'),
  bronze('Bronze League'),
  unranked('Unranked');

  const League(this.label);
  final String label;
}

/// Every number and rule in the game, in one place. Pure functions only:
/// given the same inputs they always return the same answer, which is what
/// makes them easy to test (see test/domain/game_rules_test.dart).
class GameRules {
  GameRules._();

  // ---- Hearts --------------------------------------------------------------
  static const maxHearts = 5;
  static const heartRegen = Duration(minutes: 30);
  static const heartRefillCost = 120;
  static const practiceSize = 3;

  // ---- XP ------------------------------------------------------------------
  static const hintCost = 10;
  static const lessonBonus = 10;
  static const quizPassBonus = 30;

  // ---- Quizzes -------------------------------------------------------------
  static const quizSize = 10;
  static const quizPassMark = 0.8;

  // ---- Leagues (draft cut-offs from the plan) ------------------------------
  static const goldCutoff = 10;
  static const silverCutoff = 50;

  static int defaultXpReward(QuestionType type, Difficulty difficulty) {
    return switch ((type, difficulty)) {
      (QuestionType.mcq, Difficulty.easy) => 10,
      (QuestionType.mcq, Difficulty.medium) => 15,
      (QuestionType.mcq, Difficulty.hard) => 20,
      (QuestionType.coding, Difficulty.easy) => 20,
      (QuestionType.coding, Difficulty.medium) => 25,
      (QuestionType.coding, Difficulty.hard) => 35,
    };
  }

  /// XP for one answer. Wrong answers, viewed solutions, and anything outside
  /// a real lesson or quiz (review, practice, replays) earn nothing.
  static int xpForAnswer({
    required Question question,
    required bool correct,
    required bool solutionViewed,
    required bool awardsXp,
  }) {
    if (!awardsXp || !correct || solutionViewed) return 0;
    return question.xpReward;
  }

  // ---- Levels --------------------------------------------------------------
  // Level L starts at 60 * (L-1)^2 XP: 0, 60, 240, 540, 960, 1500, 2160, ...
  // Levels follow the single XP number, so spending XP can drop a level.

  static int levelForXp(int xp) => 1 + math.sqrt(math.max(0, xp) / 60).floor();
  static int xpForLevel(int level) => 60 * (level - 1) * (level - 1);

  /// 0.0-1.0 progress from the current level to the next.
  static double levelProgress(int xp) {
    final level = levelForXp(xp);
    final start = xpForLevel(level);
    final end = xpForLevel(level + 1);
    return (xp - start) / (end - start);
  }

  static String skillLabel(int level) {
    if (level <= 3) return 'Beginner';
    if (level <= 8) return 'Intermediate';
    return 'Advanced';
  }

  static League leagueForRank(int? rank) {
    if (rank == null) return League.unranked;
    if (rank <= goldCutoff) return League.gold;
    if (rank <= silverCutoff) return League.silver;
    return League.bronze;
  }

  // ---- Hearts over time ----------------------------------------------------

  /// Adds any hearts that have regenerated by [now].
  static ({int hearts, DateTime? nextHeartAt}) regenerate({
    required int hearts,
    required DateTime? nextHeartAt,
    required DateTime now,
  }) {
    var h = hearts;
    var next = nextHeartAt;
    while (h < maxHearts && next != null && !now.isBefore(next)) {
      h++;
      next = h < maxHearts ? next.add(heartRegen) : null;
    }
    if (h >= maxHearts) next = null;
    return (hearts: h, nextHeartAt: next);
  }

  /// Takes one heart. The regen clock starts when the first heart is lost.
  static ({int hearts, DateTime? nextHeartAt}) loseHeart({
    required int hearts,
    required DateTime? nextHeartAt,
    required DateTime now,
  }) {
    final h = math.max(0, hearts - 1);
    final next = nextHeartAt ?? now.add(heartRegen);
    return (hearts: h, nextHeartAt: h < maxHearts ? next : null);
  }

  // ---- Streaks -------------------------------------------------------------

  static DateTime dayOf(DateTime t) => DateTime(t.year, t.month, t.day);

  /// Updates the streak when a lesson is finished at [now].
  static ({int streak, DateTime lastPracticeDay}) recordPractice({
    required int streak,
    required DateTime? lastPracticeDay,
    required DateTime now,
  }) {
    final today = dayOf(now);
    if (lastPracticeDay == null) return (streak: 1, lastPracticeDay: today);
    final last = dayOf(lastPracticeDay);
    final gap = today.difference(last).inDays;
    if (gap <= 0) return (streak: math.max(streak, 1), lastPracticeDay: last);
    if (gap == 1) return (streak: streak + 1, lastPracticeDay: today);
    return (streak: 1, lastPracticeDay: today);
  }

  /// The streak to *display*: it drops to 0 once a whole day has been missed.
  static int effectiveStreak({required int streak, required DateTime? lastPracticeDay, required DateTime now}) {
    if (lastPracticeDay == null) return 0;
    final gap = dayOf(now).difference(dayOf(lastPracticeDay)).inDays;
    return gap <= 1 ? streak : 0;
  }
}
